#pragma once

#include <uavcan/_register/Value_1_0.h>
#include <cstddef>
#include <cstdint>
#include <optional>
#include <span>
#include <string_view>
#include "cyphal/register_description.hpp"

namespace unimoc::cyphal {

/// The register value type of uavcan.register.Access.1.0 (generated by Nunavut).
using RegisterValue = uavcan_register_Value_1_0;

/// @name Writing a register value
/// Each setter selects the union member and stores one element (or the text).
/// @{
void SetEmpty(RegisterValue& value) noexcept;
void SetString(RegisterValue& value, std::string_view text) noexcept;
void SetUnstructured(RegisterValue& value, std::span<const uint8_t> bytes) noexcept;
void SetBit(RegisterValue& value, bool bit) noexcept;
void SetNatural8(RegisterValue& value, uint8_t number) noexcept;
void SetNatural16(RegisterValue& value, uint16_t number) noexcept;
void SetNatural32(RegisterValue& value, uint32_t number) noexcept;
void SetReal32(RegisterValue& value, float number) noexcept;
/// @}

/// True when the value holds no data (a read request).
[[nodiscard]] bool IsEmpty(const RegisterValue& value) noexcept;

/**
 * @brief Reads the first element of a numeric value as a float.
 *
 * Bits, signed and unsigned integers of every width and reals are accepted,
 * so a client may write a natural8 register with an integer64 value; the
 * register then checks the range.
 *
 * @return The number, or `std::nullopt` for an empty array, a string or
 *         unstructured data.
 */
[[nodiscard]] std::optional<float> GetNumber(const RegisterValue& value) noexcept;

/**
 * @brief Reads the first element of a numeric value as an integer.
 * @return The number, or `std::nullopt` when it is not numeric, not integral
 *         or outside the int64 range.
 */
[[nodiscard]] std::optional<int64_t> GetInteger(const RegisterValue& value) noexcept;

/// Text of a string value, or `std::nullopt` for another type.
[[nodiscard]] std::optional<std::string_view> GetString(const RegisterValue& value) noexcept;

/// Flags of a register reported by uavcan.register.Access.
struct RegisterFlags {
  bool is_mutable{false};     ///< The register accepts writes.
  bool is_persistent{false};  ///< The value survives a restart (after a store command for settings).
};

/// Result of a register write.
enum class RegisterWriteResult : uint8_t {
  kAccepted,      ///< The new value is in effect (or pending a restart, for port-IDs).
  kReadOnly,      ///< The register does not accept writes.
  kTypeMismatch,  ///< The value has a type the register cannot take.
  kOutOfRange,    ///< The value was rejected by the register or the settings validation.
};

/**
 * @brief A set of registers of the node (settings, ports, platform values).
 *
 * The node asks every provider in turn; indices run from 0 to Count() - 1 per
 * provider. All calls come from the Cyphal thread.
 */
class RegisterProvider {
 public:
  RegisterProvider() = default;
  virtual ~RegisterProvider() = default;

  RegisterProvider(const RegisterProvider&) = delete;
  RegisterProvider& operator=(const RegisterProvider&) = delete;
  RegisterProvider(RegisterProvider&&) = delete;
  RegisterProvider& operator=(RegisterProvider&&) = delete;

  /// Number of registers of this provider.
  [[nodiscard]] virtual std::size_t Count() const noexcept = 0;

  /// Name of the register @p index; the view must stay valid while the provider exists.
  [[nodiscard]] virtual std::string_view Name(std::size_t index) const noexcept = 0;

  /**
   * @brief Reads one register.
   * @param index Register index below Count().
   * @param value Output value.
   * @return The flags of the register.
   */
  [[nodiscard]] virtual RegisterFlags Read(std::size_t index, RegisterValue& value) const noexcept = 0;

  /**
   * @brief Writes one register.
   * @param index Register index below Count().
   * @param value New value; never empty.
   * @return The outcome; the node answers with the value after the write.
   */
  [[nodiscard]] virtual RegisterWriteResult Write(std::size_t index, const RegisterValue& value) noexcept = 0;

  /**
   * @brief Describes one register for the register description file.
   * @param index Register index below Count().
   * @return Unit, limits, effect and help; empty when the provider has none.
   */
  [[nodiscard]] virtual RegisterDescription Describe(std::size_t /*index*/) const noexcept { return {}; }
};

}  // namespace unimoc::cyphal
